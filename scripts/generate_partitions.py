#!/usr/bin/env python3
"""
Generate partitions.csv for ESP32 PhotoFrame based on sdkconfig settings.

Reads CONFIG_USE_INTERNAL_FLASH_STORAGE and CONFIG_ESPTOOLPY_FLASHSIZE_*
from one or more config files to determine the appropriate partition layout.

Usage:
    python3 generate_partitions.py --sdkconfig sdkconfig.defaults boards/sdkconfig.defaults.board --output partitions.csv
"""

import argparse
import sys

FLASH_SIZE_MAP = {
    "CONFIG_ESPTOOLPY_FLASHSIZE_8MB=y": 8,
    "CONFIG_ESPTOOLPY_FLASHSIZE_16MB=y": 16,
    "CONFIG_ESPTOOLPY_FLASHSIZE_32MB=y": 32,
    "CONFIG_ESPTOOLPY_FLASHSIZE_64MB=y": 64,
    "CONFIG_ESPTOOLPY_FLASHSIZE_128MB=y": 128,
}

# No OTA: a single factory app at 0x20000 takes the space of the former two
# OTA slots. nvs, phy_init, coredump and storage keep their previous offsets
# (0xf000-0x11000, the former otadata, stays unused) so a full reflash with
# this table does not move existing NVS or filesystem data. The coredump
# partition fills the gap up to the 64 KiB-aligned app; 56 KiB holds the
# crashed task plus CONFIG_ESP_COREDUMP_MAX_TASKS_NUM others.
HEADER = """\
# Generated by scripts/generate_partitions.py - do not edit manually
# Name,   Type, SubType, Offset,  Size, Flags
nvs,      data, nvs,     0x9000,  0x6000,
phy_init, data, phy,     0x11000, 0x1000,
coredump, data, coredump,0x12000, 0xe000,
"""


def parse_config_files(paths):
    use_internal_flash = False
    flash_size_mb = 16  # default

    for path in paths:
        try:
            with open(path) as f:
                for line in f:
                    line = line.strip()
                    if line == "CONFIG_USE_INTERNAL_FLASH_STORAGE=y":
                        use_internal_flash = True
                    elif line in FLASH_SIZE_MAP:
                        flash_size_mb = FLASH_SIZE_MAP[line]
        except FileNotFoundError:
            print(f"Warning: config file not found: {path}", file=sys.stderr)

    return use_internal_flash, flash_size_mb


def generate_csv(use_internal_flash, flash_size_mb):
    csv = HEADER

    if use_internal_flash:
        stg_offset = 0x520000 if flash_size_mb == 8 else 0x720000
        csv += f"factory,  app,  factory, 0x20000,  {stg_offset - 0x20000:#010x},\n"
        # Storage extends from the end of the app to the end of flash. Sized
        # from the offset, not a round MB count: the old (flash_mb - 8) MB
        # sizing left the 896 KB between 0x720000 and the 8 MB boundary
        # unaddressed. After a full reflash grow_on_mount (storage.c) expands
        # the filesystem in place.
        stg_size = flash_size_mb * 1024 * 1024 - stg_offset
        csv += f"storage,  data, littlefs,{stg_offset:#08x}, {stg_size:#010x},\n"
        print(
            f"Partition table: internal flash storage enabled "
            f"({flash_size_mb}MB flash, storage size: {stg_size:#010x})",
            file=sys.stderr,
        )
    else:
        # The app takes the span the two former OTA slots covered
        # (2 x 0x78000 per MB, i.e. 0xF00000 for 16 MB).
        app_size = flash_size_mb * 0xF0000
        csv += f"factory,  app,  factory, 0x20000,  {app_size:#010x},\n"
        print(
            f"Partition table: no internal flash storage "
            f"({flash_size_mb}MB flash, app size: {app_size:#010x})",
            file=sys.stderr,
        )

    return csv


def main():
    parser = argparse.ArgumentParser(
        description="Generate partitions.csv for ESP32 PhotoFrame"
    )
    parser.add_argument(
        "--sdkconfig",
        nargs="+",
        required=True,
        help="One or more sdkconfig/defaults files to read",
    )
    parser.add_argument("--output", required=True, help="Path to write partitions.csv")
    args = parser.parse_args()

    use_internal_flash, flash_size_mb = parse_config_files(args.sdkconfig)
    csv = generate_csv(use_internal_flash, flash_size_mb)

    with open(args.output, "w") as f:
        f.write(csv)

    return 0


if __name__ == "__main__":
    sys.exit(main())
