#!/usr/bin/env python3
"""Regenerate src/styles/mdi-subset.css: the Material Design Icons used by the device UI.

The device page must work on a hotspot or LAN with no internet, so the icon font
cannot come from a CDN. The firmware serves a fixed list of embedded files
(main/CMakeLists.txt), so the font is subset to the icons actually referenced and
inlined into the stylesheet as a base64 woff2 (~10 KB).

Run after adding or removing an `mdi-*` icon name in src/ (needs fonttools + brotli):

    npm pack @mdi/font@7.4.47 && tar xzf mdi-font-7.4.47.tgz       # somewhere outside the repo
    python3 scripts/build-mdi-subset.py --mdi-dir <path>/package

Icons: Pictogrammers Material Design Icons 7.4.47 (Apache-2.0); see docs/THIRD-PARTY.md.
"""

import argparse
import base64
import io
import re
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "styles" / "mdi-subset.css"
NAME_RE = re.compile(r"mdi-[a-z0-9]+(?:-[a-z0-9]+)*")
# Not icons: the base class, and CSS helpers of the full stylesheet.
NOT_ICONS = {"mdi-set"}


def used_icon_names():
    names = set()
    for path in (ROOT / "src").rglob("*"):
        if path.suffix in {".vue", ".js"} and path.name != OUT.name:
            names.update(NAME_RE.findall(path.read_text(encoding="utf-8")))
    # Vuetify draws its own controls (checkboxes, selects, pagination...) from these.
    vuetify_set = ROOT / "node_modules" / "vuetify" / "lib" / "iconsets" / "mdi.js"
    names.update(NAME_RE.findall(vuetify_set.read_text(encoding="utf-8")))
    return names - NOT_ICONS


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mdi-dir", required=True, type=Path, help="extracted @mdi/font package")
    args = parser.parse_args()

    css = (args.mdi_dir / "css" / "materialdesignicons.css").read_text(encoding="utf-8")
    codepoints = {
        name: int(code, 16)
        for name, code in re.findall(r'\.(mdi-[a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9A-F]+)"', css)
    }

    wanted = used_icon_names()
    missing = sorted(n for n in wanted if n not in codepoints)
    if missing:
        sys.exit(f"names not in @mdi/font (typo, or not an icon): {', '.join(missing)}")
    icons = sorted(wanted)

    font = TTFont(args.mdi_dir / "fonts" / "materialdesignicons-webfont.ttf")
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []
    options.name_IDs = []
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[codepoints[n] for n in icons])
    subsetter.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    data = base64.b64encode(buf.getvalue()).decode("ascii")

    lines = [
        "/* Generated by scripts/build-mdi-subset.py -- do not edit by hand.",
        f"   Material Design Icons 7.4.47 (Apache-2.0), {len(icons)} icons, inlined so the",
        "   page needs no network. */",
        "@font-face {",
        '  font-family: "Material Design Icons";',
        f'  src: url("data:font/woff2;base64,{data}") format("woff2");',
        "  font-weight: normal;",
        "  font-style: normal;",
        "  font-display: block;",
        "}",
        "",
        ".mdi:before,",
        ".mdi-set {",
        "  display: inline-block;",
        '  font: normal normal normal 24px/1 "Material Design Icons";',
        "  font-size: inherit;",
        "  text-rendering: auto;",
        "  line-height: inherit;",
        "  -webkit-font-smoothing: antialiased;",
        "  -moz-osx-font-smoothing: grayscale;",
        "}",
        "",
    ]
    for name in icons:
        lines += [f".{name}::before {{", f'  content: "\\{codepoints[name]:X}";', "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(icons)} icons, woff2 {len(buf.getvalue())} bytes -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
